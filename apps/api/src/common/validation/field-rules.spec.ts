import { isIsoDateTime } from './field-rules';

describe('isIsoDateTime', () => {
  it.each([
    '2026-04-09T10:05:00+02:00',
    '2026-04-09T10:05:00.123Z',
    '2026-07-14T21:00:00+05:30',
    '2026-01-01T00:30:00-03:00',
    '2024-02-29T23:59:59+14:00',
  ])('accepts %s', (value) => {
    expect(isIsoDateTime(value)).toBe(true);
  });

  it.each([
    '2026-04-09T10:05:00',
    '2026-04-09T10:05+02:00',
    '2026-04-09 10:05:00+02:00',
    '2026-02-29T10:05:00+02:00',
    '2026-04-31T10:05:00Z',
    '2026-04-09T24:00:00Z',
    '2026-04-09T10:60:00Z',
    '2026-04-09T10:05:00+24:00',
    '2026-04-09T10:05:00.1234Z',
    '',
    1_775_721_900_000,
    null,
  ])('refuses %j', (value) => {
    expect(isIsoDateTime(value)).toBe(false);
  });
});
