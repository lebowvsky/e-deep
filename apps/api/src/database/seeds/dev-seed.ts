import type { LevelCode, SeedDive, SeedDiver } from './dev-seed.types';
import { SeedEnvironment } from './seed-environment';

const LOCAL_HOSTS: ReadonlySet<string> = new Set(['localhost', '127.0.0.1', '::1']);
/** Timestamp of every seeded UUIDv7 (the first dive of the log). */
const SEED_IDS_EPOCH_MS = Date.UTC(2019, 5, 1);
const ISO_OFFSET = /([+-])(\d{2}):(\d{2})$/;

const logger = new Logger('DevSeed');

class SeedRefusedError extends Error {
  override readonly name = 'SeedRefusedError';
}

interface SeedReport {
  divers: number;
  accounts: number;
  sites: number;
  buddies: number;
  dives: number;
  deletedDives: number;
}

/**
 * Deterministic UUIDv7, as a client would generate it but reproducible: a fixed timestamp, then a
 * sequence number in the random bits. Same ids at every run, as long as the data order is stable.
 */
class SeedIds {
  private sequence = 0;

  next(): string {
    this.sequence += 1;
    const timestamp = SEED_IDS_EPOCH_MS.toString(16).padStart(12, '0');
    const sequence = this.sequence.toString(16).padStart(15, '0');
    return `${timestamp.slice(0, 8)}-${timestamp.slice(8)}-7000-8${sequence.slice(0, 3)}-${sequence.slice(3)}`;
  }
}

class DevSeeder {
  private readonly settings: SyncSettings = { purgeHorizonDays: DEFAULT_PURGE_HORIZON_DAYS };
  private readonly divers: DiversService;
  private readonly sites: DiveSitesService;
  private readonly buddies: BuddiesService;
  private readonly dives: DivesService;
  private readonly consents: ConsentsService;
  private readonly ids = new SeedIds();
  private readonly diverIds = new Map<string, string>();
  private readonly levelIds = new Map<LevelCode, string>();

  /** @param passwordHash Argon2id hash of `SEED_PASSWORD`, already checked against the policy. */
  constructor(
    private readonly dataSource: DataSource,
    private readonly passwordHash: string,
  ) {
    this.divers = new DiversService(dataSource);
    this.consents = new ConsentsService(dataSource, new AuthEventsService(dataSource));
    this.sites = new DiveSitesService(dataSource, this.settings);
    this.buddies = new BuddiesService(dataSource, this.settings);
    this.dives = new DivesService(dataSource, this.settings);
  }

  async run(): Promise<SeedReport> {
    const report: SeedReport = {
      divers: 0,
      accounts: 0,
      sites: 0,
      buddies: 0,
      dives: 0,
      deletedDives: 0,
    };
    await this.reset();
    await this.loadLevels();

    // Accounts first: buddies of one diver may be linked to another diver's account.
    for (const diver of SEED_DIVERS) {
      const created = await this.divers.create({
        firstName: diver.firstName,
        lastName: diver.lastName,
        certificationLevelId: this.levelId(diver.levelCode),
        avatarUrl: null,
      });
      this.diverIds.set(diver.key, created.id);
      report.divers += 1;
      await this.seedAccount(diver.email, created.id);
      report.accounts += 1;
    }

    for (const diver of SEED_DIVERS) {
      await this.seedLogbook(diver, report);
    }
    return report;
  }

  /**
   * Empties the dive log and the diver accounts; `certification_levels` (migration seed) and the
   * staff accounts (`account:create-staff`, no diver) are kept, with their sessions and trail: a
   * re-seed never signs an operator out nor erases what they did.
   *
   * The divers are deleted, not truncated: their accounts, sessions and trail follow by cascade
   * (`TRUNCATE divers` would have to cascade to the whole `accounts` table). The events without an
   * account (unknown email, deleted account) only concern divers: cleared too.
   */
  private async reset(): Promise<void> {
    await this.dataSource.query(
      'TRUNCATE consents, dive_observations, dive_buddies, dive_participations, dive_events, buddies, dive_sites',
    );
    await this.dataSource.query('DELETE FROM divers');
    await this.dataSource.query('DELETE FROM auth_events WHERE account_id IS NULL');
  }

  /** A diver account (D36) with a consent at the current policy version (D38): `/welcome` done. */
  private async seedAccount(email: string, diverId: string): Promise<void> {
    await this.dataSource.manager.insert(Account, {
      diverId,
      email,
      passwordHash: this.passwordHash,
      role: 'diver',
    });
    const { id: accountId } = await this.dataSource.manager.findOneByOrFail(Account, { email });
    await this.consents.grant({
      accountId,
      diverId,
      purpose: 'health_data_processing',
      policyVersion: CURRENT_HEALTH_POLICY_VERSION,
    });
  }

  private async loadLevels(): Promise<void> {
    const levels = await this.dataSource.manager.findBy(CertificationLevel, { agency: 'FFESSM' });
    for (const level of levels) {
      this.levelIds.set(level.code as LevelCode, level.id);
    }
  }

  private async seedLogbook(diver: SeedDiver, report: SeedReport): Promise<void> {
    const diverId = this.required(this.diverIds, diver.key);
    const lastPulledAt = new Date();
    const siteIds = new Map<string, string>();
    const buddyIds = new Map<string, string>();

    for (const site of diver.sites) {
      const id = this.ids.next();
      await this.sites.upsert(
        diverId,
        {
          id,
          name: site.name,
          locality: site.locality,
          region: site.region,
          area: site.area,
          latitude: site.latitude,
          longitude: site.longitude,
          type: site.type ?? null,
          depthMinM: site.depthMinM ?? null,
          depthMaxM: site.depthMaxM ?? null,
          accessNotes: site.accessNotes ?? null,
          createdVia: site.latitude === null ? 'quick' : 'full',
          baseUpdatedAt: null,
          deletedAt: null,
        },
        lastPulledAt,
      );
      siteIds.set(site.key, id);
      report.sites += 1;
    }

    for (const buddy of diver.buddies) {
      const id = this.ids.next();
      await this.buddies.upsert(
        diverId,
        {
          id,
          firstName: buddy.firstName,
          lastName: buddy.lastName,
          linkedDiverId:
            buddy.linkedDiverKey === undefined
              ? null
              : this.required(this.diverIds, buddy.linkedDiverKey),
          certificationLevelId:
            buddy.levelCode === undefined ? null : this.levelId(buddy.levelCode),
          baseUpdatedAt: null,
          deletedAt: null,
        },
        lastPulledAt,
      );
      buddyIds.set(buddy.key, id);
      report.buddies += 1;
    }

    // Oldest first, so `updated_at` (the sync cursor) follows the logbook order.
    const dives = [...diver.dives].sort(
      (left, right) => Date.parse(left.date) - Date.parse(right.date),
    );
    for (const dive of dives) {
      const eventId = this.ids.next();
      await this.dives.upsertDive(
        diverId,
        {
          event: {
            id: eventId,
            siteId: this.required(siteIds, dive.siteKey),
            ...parseLocalDate(dive),
            ...NO_EVENT_CONDITIONS,
            ...dive.detail?.conditions,
            baseUpdatedAt: null,
            deletedAt: null,
          },
          // No level sent: the diver's current level is copied (D-09).
          participation: {
            id: this.ids.next(),
            maxDepthM: dive.maxDepthM,
            durationMin: dive.durationMin,
            waterTemperatureC: dive.waterTemperatureC,
            visibilityM: dive.visibilityM,
            gasMix: dive.gasMix,
            hasDecompression: dive.hasDecompression,
            stopsOk: dive.stopsOk,
            notes: dive.notes,
            ...NO_PARTICIPATION_DETAIL,
            ...dive.detail?.participation,
            baseUpdatedAt: null,
            deletedAt: null,
          },
          buddyIds: dive.buddyKeys.map((key) => this.required(buddyIds, key)),
          observations: dive.detail?.observations ?? [],
        },
        lastPulledAt,
      );
      report.dives += 1;
      if (dive.deleted === true) {
        await this.dives.deleteDive(diverId, eventId);
        report.deletedDives += 1;
      }
    }
  }

  private levelId(code: LevelCode): string {
    return this.required(this.levelIds, code);
  }

  private required<K, V>(map: ReadonlyMap<K, V>, key: K): V {
    const value = map.get(key);
    if (value === undefined) {
      throw new Error('Inconsistent seed data');
    }
    return value;
  }
}

/** Instant and offset of a dive from its local date with offset (`2026-04-08T10:30:00+02:00`). */
function parseLocalDate(dive: SeedDive): { startedAt: Date; utcOffsetMinutes: number } {
  const offset = ISO_OFFSET.exec(dive.date);
  if (offset === null) {
    throw new Error('Inconsistent seed data');
  }
  const [, sign, hours, minutes] = offset;
  const absolute = Number(hours) * 60 + Number(minutes);
  return {
    startedAt: new Date(dive.date),
    utcOffsetMinutes: sign === '-' ? -absolute : absolute,
  };
}

/**
 * The hash of `SEED_PASSWORD`, once it passes the password policy (D35) for every seeded identity:
 * the seed accounts are signed into like any other.
 *
 * @throws {DomainValidationError} with the policy codes only, never the value.
 */
async function seedPasswordHash(password: string): Promise<string> {
  const policy = new PasswordPolicy(await loadCompromisedPasswords());
  for (const { email, firstName, lastName } of SEED_DIVERS) {
    policy.assertAcceptable(password, { email, firstName, lastName }, 'password');
  }
  return (await PasswordHasher.create()).hash(password);
}

/** Error detail safe to log: class name, generic domain message or violated constraint name. */
function describeError(error: unknown): string {
  // Names the invalid variables only, never their values.
  if (error instanceof EnvironmentValidationError) {
    return error.message;
  }
  if (error instanceof DomainValidationError) {
    const codes = Object.values(error.fieldErrors).flat().join(', ');
    return `SEED_PASSWORD refused by the password policy: ${codes}`;
  }
  if (error instanceof DomainError || error instanceof SeedRefusedError) {
    return `${errorClassName(error)}: ${error.message}`;
  }
  if (error instanceof QueryFailedError) {
    const driverError: unknown = error.driverError;
    const constraint =
      typeof driverError === 'object' && driverError !== null && 'constraint' in driverError
        ? String(driverError.constraint)
        : 'unknown constraint';
    return `${errorClassName(error)} (${constraint})`;
  }
  return errorClassName(error);
}

async function main(): Promise<void> {
  const environment = loadScriptEnvironment(SeedEnvironment);
  // Read after `loadScriptEnvironment`, which loads the `.env` file into `process.env`.
  if (process.env['NODE_ENV'] === 'production') {
    throw new SeedRefusedError('The dev seed never runs in production');
  }
  if (!LOCAL_HOSTS.has(environment.DATABASE_HOST)) {
    throw new SeedRefusedError('The dev seed only runs against a local database');
  }

  const dataSource = new DataSource({
    ...buildDataSourceOptions(environment),
    entities: [join(__dirname, '..', '..', '**', '*.entity.js')],
  });
  await dataSource.initialize();
  try {
    if (await dataSource.showMigrations()) {
      throw new SeedRefusedError('Pending migrations: run `pnpm migration:run` first');
    }
    // Checked before the reset: a refused password leaves the database untouched.
    const passwordHash = await seedPasswordHash(environment.SEED_PASSWORD);
    const report = await new DevSeeder(dataSource, passwordHash).run();
    logger.log(
      `Seeded ${String(report.divers)} divers (${String(report.accounts)} accounts), ${String(report.sites)} sites, ${String(report.buddies)} buddies, ` +
        `${String(report.dives)} dives (${String(report.deletedDives)} deleted)`,
    );
  } finally {
    await dataSource.destroy();
  }
}

main().catch((error: unknown) => {
  logger.error(`Seed failed (${describeError(error)})`);
  process.exitCode = 1;
});
