/**
 * Development seed: `pnpm db:seed` (builds, then runs `dist/database/seeds/dev-seed.js`).
 *
 * Empties the dive log tables (the certification levels reference data is kept) and fills them with
 * fictitious divers, sites, buddies and dives. Goes through the services, so every invariant (owner,
 * level snapshot, dive team, triggers) applies. Re-runnable: same final state every time.
 *
 * Staff accounts (`account:create-staff`) survive a re-seed, with their sessions and trail: only
 * the divers, their accounts (by cascade) and their dive logs are replaced.
 *
 * Each diver gets a real account (`<key>@example.test`, D44) with the password `SEED_PASSWORD`
 * (required, no default, checked against the password policy before anything is written) and a
 * health data consent at the current policy version, so the dive log is reachable at once.
 *
 * Ids are deterministic UUIDv7 (`SeedIds`): a seeded dive keeps its URL across runs. Divers are the
 * exception, their id is generated by the database.
 *
 * Refuses any database that is not local, and `NODE_ENV=production`. GDPR: only counts and error
 * class names are logged, never an email nor the password.
 */
import { join } from 'node:path';
import { Logger } from '@nestjs/common';
import { DataSource, QueryFailedError } from 'typeorm';
import { DomainError, DomainValidationError } from '../../common/errors/domain-errors';
import { errorClassName } from '../../common/logging/error-class-name';
import { DEFAULT_PURGE_HORIZON_DAYS, type SyncSettings } from '../../common/sync/sync-settings';
import { EnvironmentValidationError } from '../../config/environment';
import { Account } from '../../modules/accounts/account.entity';
import { AuthEventsService } from '../../modules/auth/auth-events.service';
import { loadCompromisedPasswords } from '../../modules/auth/password/compromised-passwords';
import { PasswordHasher } from '../../modules/auth/password/password-hasher';
import { PasswordPolicy } from '../../modules/auth/password/password-policy';
import { BuddiesService } from '../../modules/buddies/buddies.service';
import { CertificationLevel } from '../../modules/certification-levels/certification-level.entity';
import { ConsentsService } from '../../modules/consents/consents.service';
import { CURRENT_HEALTH_POLICY_VERSION } from '../../modules/consents/health-policy-versions';
import { DiveSitesService } from '../../modules/dive-sites/dive-sites.service';
import { DiversService } from '../../modules/divers/divers.service';
import { NO_EVENT_CONDITIONS, NO_PARTICIPATION_DETAIL } from '../../modules/dives/dive.types';
import { DivesService } from '../../modules/dives/dives.service';
