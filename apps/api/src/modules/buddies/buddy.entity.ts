import {
  Check,
  Column,
  Entity,
  Index,
  JoinColumn,
  ManyToOne,
  PrimaryColumn,
  Unique,
  type Relation,
} from 'typeorm';
import { SyncedEntity } from '../../common/database/timestamped.entity';
import { Diver } from '../divers/diver.entity';

/**
 * Private contact of a diver. The optional link to an E-Deep account grants no access to the
 * owner's dives.
 */
@Entity({ name: 'buddies' })
// Target of the composite FK from `dive_buddies`; also covers the `owner_id` FK.
@Unique('uq_buddies__owner_id_id', ['ownerId', 'id'])
@Index('uq_buddies__owner_id_linked_diver_id', ['ownerId', 'linkedDiverId'], {
  unique: true,
  where: 'linked_diver_id IS NOT NULL AND deleted_at IS NULL',
})
@Index('idx_buddies__owner_id_updated_at_id', ['ownerId', 'updatedAt', 'id'])
@Index('idx_buddies__linked_diver_id', ['linkedDiverId'], {
  where: 'linked_diver_id IS NOT NULL',
})
@Check('ck_buddies__first_name', 'char_length(btrim(first_name)) BETWEEN 1 AND 100')
@Check('ck_buddies__last_name', 'char_length(btrim(last_name)) BETWEEN 1 AND 100')
@Check('ck_buddies__not_self', 'linked_diver_id IS NULL OR linked_diver_id <> owner_id')
export class Buddy extends SyncedEntity {
  /** UUIDv7 generated by the client (offline creation). */
  @PrimaryColumn('uuid', { name: 'id', primaryKeyConstraintName: 'pk_buddies' })
  id: string;

  @Column({ type: 'uuid', name: 'owner_id' })
  ownerId: string;

  @ManyToOne(() => Diver, { onDelete: 'CASCADE', nullable: false })
  @JoinColumn({ name: 'owner_id', foreignKeyConstraintName: 'fk_buddies__owner_id' })
  owner?: Relation<Diver>;

  @Column({ type: 'text', name: 'first_name' })
  firstName: string;

  @Column({ type: 'text', name: 'last_name' })
  lastName: string;

  @Column({ type: 'uuid', name: 'linked_diver_id', nullable: true })
  linkedDiverId: string | null;

  @ManyToOne(() => Diver, { onDelete: 'SET NULL', nullable: true })
  @JoinColumn({
    name: 'linked_diver_id',
    foreignKeyConstraintName: 'fk_buddies__linked_diver_id',
  })
  linkedDiver?: Relation<Diver> | null;
}
