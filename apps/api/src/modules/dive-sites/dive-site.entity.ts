import {
  Check,
  Column,
  Entity,
  Index,
  JoinColumn,
  ManyToOne,
  PrimaryColumn,
  Unique,
  type Relation,
} from 'typeorm';
import type { SiteOrigin, SiteType } from '@e-deep/shared';
import { numericTransformer } from '../../common/database/numeric.transformer';
import { SyncedEntity } from '../../common/database/timestamped.entity';
import { Diver } from '../divers/diver.entity';

/**
 * Private to its owner. No uniqueness on the name: two offline devices may create the same site.
 * A site created by its name alone has no region nor position yet (D-23). A site merged into
 * another is a tombstone that keeps its target (`merged_into_id`, D-30).
 */
@Entity({ name: 'dive_sites' })
// Target of the composite FK from `dive_events`; also covers the `owner_id` FK.
@Unique('uq_dive_sites__owner_id_id', ['ownerId', 'id'])
@Index('idx_dive_sites__owner_id_updated_at_id', ['ownerId', 'updatedAt', 'id'])
// Covers the merge FK (deletion of a target) and the reduction of the merge chains (D-30).
@Index('idx_dive_sites__owner_id_merged_into_id', ['ownerId', 'mergedIntoId'], {
  where: 'merged_into_id IS NOT NULL',
})
@Check('ck_dive_sites__name', 'char_length(btrim(name)) BETWEEN 1 AND 120')
@Check(
  'ck_dive_sites__locality',
  'locality IS NULL OR char_length(btrim(locality)) BETWEEN 1 AND 120',
)
@Check('ck_dive_sites__region', 'region IS NULL OR char_length(btrim(region)) BETWEEN 1 AND 120')
@Check('ck_dive_sites__area', 'area IS NULL OR char_length(btrim(area)) BETWEEN 1 AND 120')
@Check('ck_dive_sites__latitude', 'latitude IS NULL OR latitude BETWEEN -90 AND 90')
@Check('ck_dive_sites__longitude', 'longitude IS NULL OR longitude BETWEEN -180 AND 180')
// A position is both coordinates or none (D-23).
@Check('ck_dive_sites__position', '(latitude IS NULL) = (longitude IS NULL)')
// Details of the site (D-27, RG-31 to RG-33) and its origin (D-28, RG-34).
@Check(
  'ck_dive_sites__type',
  "type IS NULL OR type IN ('tombant', 'epave', 'sec', 'grotte', 'herbier', 'autre')",
)
@Check('ck_dive_sites__depth_min_m', 'depth_min_m IS NULL OR depth_min_m BETWEEN 0 AND 350')
@Check(
  'ck_dive_sites__depth_max_m',
  'depth_max_m IS NULL OR (depth_max_m > 0 AND depth_max_m <= 350)',
)
@Check(
  'ck_dive_sites__depth_range',
  'depth_min_m IS NULL OR depth_max_m IS NULL OR depth_min_m <= depth_max_m',
)
@Check(
  'ck_dive_sites__access_notes',
  'access_notes IS NULL OR char_length(btrim(access_notes)) BETWEEN 1 AND 2000',
)
@Check('ck_dive_sites__created_via', "created_via IN ('quick', 'full')")
// Only a tombstone has a merge target, never itself (D-30).
@Check(
  'ck_dive_sites__merged_into_id_tombstone',
  'merged_into_id IS NULL OR deleted_at IS NOT NULL',
)
@Check('ck_dive_sites__merged_into_id_not_self', 'merged_into_id IS NULL OR merged_into_id <> id')
export class DiveSite extends SyncedEntity {
  /** UUIDv7 generated by the client (offline creation). */
  @PrimaryColumn('uuid', { name: 'id', primaryKeyConstraintName: 'pk_dive_sites' })
  id: string;

  @Column({ type: 'uuid', name: 'owner_id' })
  ownerId: string;

  @ManyToOne(() => Diver, { onDelete: 'CASCADE', nullable: false })
  @JoinColumn({ name: 'owner_id', foreignKeyConstraintName: 'fk_dive_sites__owner_id' })
  owner?: Relation<Diver>;

  @Column({ type: 'text', name: 'name' })
  name: string;

  /** Town or spot the site belongs to (e.g. `Calvi`), shown before the region. Optional. */
  @Column({ type: 'text', name: 'locality', nullable: true })
  locality: string | null;

  /** `NULL` when not entered (site created by its name, D-23). */
  @Column({ type: 'text', name: 'region', nullable: true })
  region: string | null;

  /** Sea or area of the site (e.g. `Méditerranée`), free text like the region (D-20). Optional. */
  @Column({ type: 'text', name: 'area', nullable: true })
  area: string | null;

  @Column({
    type: 'numeric',
    name: 'latitude',
    precision: 8,
    scale: 6,
    nullable: true,
    transformer: numericTransformer,
  })
  latitude: number | null;

  @Column({
    type: 'numeric',
    name: 'longitude',
    precision: 9,
    scale: 6,
    nullable: true,
    transformer: numericTransformer,
  })
  longitude: number | null;

  /** RG-31; `NULL` when not entered. */
  @Column({ type: 'text', name: 'type', nullable: true })
  type: SiteType | null;

  /** Usual depths of the site, not the diver's own (RG-32): min ≤ max when both are set. */
  @Column({
    type: 'numeric',
    name: 'depth_min_m',
    precision: 4,
    scale: 1,
    nullable: true,
    transformer: numericTransformer,
  })
  depthMinM: number | null;

  @Column({
    type: 'numeric',
    name: 'depth_max_m',
    precision: 4,
    scale: 1,
    nullable: true,
    transformer: numericTransformer,
  })
  depthMaxM: number | null;

  /** « Accès & conseils » (RG-33). */
  @Column({ type: 'text', name: 'access_notes', nullable: true })
  accessNotes: string | null;

  /** Set at creation, never changed (RG-34). */
  @Column({ type: 'text', name: 'created_via' })
  createdVia: SiteOrigin;

  /**
   * Target of the merge that deleted this site (D-30): writes referencing it are redirected there.
   * Always a single hop (the merge reduces the chains).
   */
  @Column({ type: 'uuid', name: 'merged_into_id', nullable: true })
  mergedIntoId: string | null;

  /** Composite FK: the target belongs to the same owner. */
  @ManyToOne(() => DiveSite, { onDelete: 'NO ACTION', nullable: true })
  @JoinColumn([
    {
      name: 'owner_id',
      referencedColumnName: 'ownerId',
      foreignKeyConstraintName: 'fk_dive_sites__owner_id_merged_into_id',
    },
    {
      name: 'merged_into_id',
      referencedColumnName: 'id',
      foreignKeyConstraintName: 'fk_dive_sites__owner_id_merged_into_id',
    },
  ])
  mergedInto?: Relation<DiveSite>;
}
