import {
  Check,
  Column,
  Entity,
  Index,
  JoinColumn,
  ManyToOne,
  PrimaryColumn,
  Unique,
  type Relation,
} from 'typeorm';
import { numericTransformer } from '../../common/database/numeric.transformer';
import { SyncedEntity } from '../../common/database/timestamped.entity';
import { Diver } from '../divers/diver.entity';

/** Private to its owner. No uniqueness on the name: two offline devices may create the same site. */
@Entity({ name: 'dive_sites' })
// Target of the composite FK from `dive_events`; also covers the `owner_id` FK.
@Unique('uq_dive_sites__owner_id_id', ['ownerId', 'id'])
@Index('idx_dive_sites__owner_id_updated_at_id', ['ownerId', 'updatedAt', 'id'])
@Check('ck_dive_sites__name', 'char_length(btrim(name)) BETWEEN 1 AND 120')
@Check(
  'ck_dive_sites__locality',
  'locality IS NULL OR char_length(btrim(locality)) BETWEEN 1 AND 120',
)
@Check('ck_dive_sites__region', 'char_length(btrim(region)) BETWEEN 1 AND 120')
@Check('ck_dive_sites__latitude', 'latitude BETWEEN -90 AND 90')
@Check('ck_dive_sites__longitude', 'longitude BETWEEN -180 AND 180')
export class DiveSite extends SyncedEntity {
  /** UUIDv7 generated by the client (offline creation). */
  @PrimaryColumn('uuid', { name: 'id', primaryKeyConstraintName: 'pk_dive_sites' })
  id: string;

  @Column({ type: 'uuid', name: 'owner_id' })
  ownerId: string;

  @ManyToOne(() => Diver, { onDelete: 'CASCADE', nullable: false })
  @JoinColumn({ name: 'owner_id', foreignKeyConstraintName: 'fk_dive_sites__owner_id' })
  owner?: Relation<Diver>;

  @Column({ type: 'text', name: 'name' })
  name: string;

  /** Town or spot the site belongs to (e.g. `Calvi`), shown before the region. Optional. */
  @Column({ type: 'text', name: 'locality', nullable: true })
  locality: string | null;

  @Column({ type: 'text', name: 'region' })
  region: string;

  @Column({
    type: 'numeric',
    name: 'latitude',
    precision: 8,
    scale: 6,
    transformer: numericTransformer,
  })
  latitude: number;

  @Column({
    type: 'numeric',
    name: 'longitude',
    precision: 9,
    scale: 6,
    transformer: numericTransformer,
  })
  longitude: number;
}
