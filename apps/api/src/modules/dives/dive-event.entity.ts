import {
  Check,
  Column,
  Entity,
  Index,
  JoinColumn,
  ManyToOne,
  PrimaryColumn,
  type Relation,
} from 'typeorm';
import { numericTransformer } from '../../common/database/numeric.transformer';
import { SyncedEntity } from '../../common/database/timestamped.entity';
import { DiveSite } from '../dive-sites/dive-site.entity';
import { Diver } from '../divers/diver.entity';
import type { CurrentStrength, EntryType, SeaState, TimeOfDay, Weather } from './dive-detail-lists';

/**
 * Data shared by the dive team: site, instant and local time. In the MVP an event has exactly one
 * participation, its creator's (service rule, lifted once dives can be shared).
 */
@Entity({ name: 'dive_events' })
// Sync pull; also covers the `creator_id` FK.
@Index('idx_dive_events__creator_id_updated_at_id', ['creatorId', 'updatedAt', 'id'])
// Composite FK to the site: deletion check of a used site, purge of sites.
@Index('idx_dive_events__creator_id_site_id', ['creatorId', 'siteId'])
@Check('ck_dive_events__utc_offset_minutes', 'utc_offset_minutes BETWEEN -720 AND 840')
@Check('ck_dive_events__entry_type', "entry_type IS NULL OR entry_type IN ('BOAT', 'SHORE')")
@Check('ck_dive_events__time_of_day', "time_of_day IS NULL OR time_of_day IN ('DAY', 'NIGHT')")
@Check(
  'ck_dive_events__weather',
  "weather IS NULL OR weather IN ('SUNNY', 'CLOUDY', 'OVERCAST', 'RAIN')",
)
@Check(
  'ck_dive_events__air_temperature_c',
  'air_temperature_c IS NULL OR air_temperature_c BETWEEN -40 AND 60',
)
@Check(
  'ck_dive_events__sea_state',
  "sea_state IS NULL OR sea_state IN ('CALM', 'SLIGHT', 'MODERATE', 'ROUGH')",
)
@Check(
  'ck_dive_events__current_strength',
  "current_strength IS NULL OR current_strength IN ('NONE', 'WEAK', 'MODERATE', 'STRONG')",
)
@Check(
  'ck_dive_events__dive_center',
  'dive_center IS NULL OR char_length(btrim(dive_center)) BETWEEN 1 AND 120',
)
export class DiveEvent extends SyncedEntity {
  /** UUIDv7 generated by the client (offline creation). */
  @PrimaryColumn('uuid', { name: 'id', primaryKeyConstraintName: 'pk_dive_events' })
  id: string;

  @Column({ type: 'uuid', name: 'creator_id' })
  creatorId: string;

  // CASCADE is only correct while an event has a single participant (MVP): see D-08.
  @ManyToOne(() => Diver, { onDelete: 'CASCADE', nullable: false })
  @JoinColumn({ name: 'creator_id', foreignKeyConstraintName: 'fk_dive_events__creator_id' })
  creator?: Relation<Diver>;

  @Column({ type: 'uuid', name: 'site_id' })
  siteId: string;

  /** Composite FK: the site must belong to the creator. */
  @ManyToOne(() => DiveSite, { onDelete: 'RESTRICT', nullable: false })
  @JoinColumn([
    {
      name: 'creator_id',
      referencedColumnName: 'ownerId',
      foreignKeyConstraintName: 'fk_dive_events__creator_id_site_id',
    },
    {
      name: 'site_id',
      referencedColumnName: 'id',
      foreignKeyConstraintName: 'fk_dive_events__creator_id_site_id',
    },
  ])
  site?: Relation<DiveSite>;

  @Column({ type: 'timestamptz', name: 'started_at' })
  startedAt: Date;

  /** Offset of the dive's local time; displayed time = `started_at + utc_offset_minutes` (D-10). */
  @Column({ type: 'smallint', name: 'utc_offset_minutes' })
  utcOffsetMinutes: number;

  // Type and conditions, shared by the dive team and edited by the creator only (D-13, RG-29).
  // Every column is nullable without default: `NULL` = not entered.

  /** Boat or shore entry. */
  @Column({ type: 'text', name: 'entry_type', nullable: true })
  entryType: EntryType | null;

  /** Declared, never derived from the local time (D-13). */
  @Column({ type: 'text', name: 'time_of_day', nullable: true })
  timeOfDay: TimeOfDay | null;

  @Column({ type: 'text', name: 'weather', nullable: true })
  weather: Weather | null;

  @Column({
    type: 'numeric',
    name: 'air_temperature_c',
    precision: 3,
    scale: 1,
    nullable: true,
    transformer: numericTransformer,
  })
  airTemperatureC: number | null;

  @Column({ type: 'text', name: 'sea_state', nullable: true })
  seaState: SeaState | null;

  /** Not `current`, ambiguous in SQL (D-13). */
  @Column({ type: 'text', name: 'current_strength', nullable: true })
  currentStrength: CurrentStrength | null;

  /** Dive centre (free text, D-18): location data, not the club of D-08. */
  @Column({ type: 'text', name: 'dive_center', nullable: true })
  diveCenter: string | null;
}
