import {
  Check,
  Column,
  Entity,
  Index,
  JoinColumn,
  ManyToOne,
  PrimaryColumn,
  type Relation,
} from 'typeorm';
import { SyncedEntity } from '../../common/database/timestamped.entity';
import { DiveSite } from '../dive-sites/dive-site.entity';
import { Diver } from '../divers/diver.entity';

/**
 * Data shared by the dive team: site, instant and local time. In the MVP an event has exactly one
 * participation, its creator's (service rule, lifted once dives can be shared).
 */
@Entity({ name: 'dive_events' })
// Sync pull; also covers the `creator_id` FK.
@Index('idx_dive_events__creator_id_updated_at_id', ['creatorId', 'updatedAt', 'id'])
// Composite FK to the site: deletion check of a used site, purge of sites.
@Index('idx_dive_events__creator_id_site_id', ['creatorId', 'siteId'])
@Check('ck_dive_events__utc_offset_minutes', 'utc_offset_minutes BETWEEN -720 AND 840')
export class DiveEvent extends SyncedEntity {
  /** UUIDv7 generated by the client (offline creation). */
  @PrimaryColumn('uuid', { name: 'id', primaryKeyConstraintName: 'pk_dive_events' })
  id: string;

  @Column({ type: 'uuid', name: 'creator_id' })
  creatorId: string;

  // CASCADE is only correct while an event has a single participant (MVP): see D-08.
  @ManyToOne(() => Diver, { onDelete: 'CASCADE', nullable: false })
  @JoinColumn({ name: 'creator_id', foreignKeyConstraintName: 'fk_dive_events__creator_id' })
  creator?: Relation<Diver>;

  @Column({ type: 'uuid', name: 'site_id' })
  siteId: string;

  /** Composite FK: the site must belong to the creator. */
  @ManyToOne(() => DiveSite, { onDelete: 'RESTRICT', nullable: false })
  @JoinColumn([
    {
      name: 'creator_id',
      referencedColumnName: 'ownerId',
      foreignKeyConstraintName: 'fk_dive_events__creator_id_site_id',
    },
    {
      name: 'site_id',
      referencedColumnName: 'id',
      foreignKeyConstraintName: 'fk_dive_events__creator_id_site_id',
    },
  ])
  site?: Relation<DiveSite>;

  @Column({ type: 'timestamptz', name: 'started_at' })
  startedAt: Date;

  /** Offset of the dive's local time; displayed time = `started_at + utc_offset_minutes` (D-10). */
  @Column({ type: 'smallint', name: 'utc_offset_minutes' })
  utcOffsetMinutes: number;
}
