import {
  Check,
  Column,
  Entity,
  Index,
  JoinColumn,
  ManyToOne,
  PrimaryColumn,
  Unique,
  type Relation,
} from 'typeorm';
import { numericTransformer } from '../../common/database/numeric.transformer';
import { SyncedEntity } from '../../common/database/timestamped.entity';
import { CertificationLevel } from '../certification-levels/certification-level.entity';
import { Diver } from '../divers/diver.entity';
import { DiveEvent } from './dive-event.entity';
import type { GasMix } from './gas-mix';

/** Health data (GDPR art. 9): one diver's own measures for a dive event. Never log its values. */
@Entity({ name: 'dive_participations' })
// Not partial: a participation removed then re-added is restored, not recreated. Covers the event FK.
@Unique('uq_dive_participations__dive_event_id_diver_id', ['diveEventId', 'diverId'])
// Target of the composite FK from `dive_buddies`; also covers the `diver_id` FK.
@Unique('uq_dive_participations__diver_id_id', ['diverId', 'id'])
@Index('idx_dive_participations__diver_id_dive_event_id', ['diverId', 'diveEventId'], {
  where: 'deleted_at IS NULL',
})
@Index('idx_dive_participations__diver_id_updated_at_id', ['diverId', 'updatedAt', 'id'])
@Check('ck_dive_participations__max_depth_m', 'max_depth_m > 0 AND max_depth_m <= 350')
@Check('ck_dive_participations__duration_min', 'duration_min > 0 AND duration_min <= 1440')
@Check(
  'ck_dive_participations__water_temperature_c',
  'water_temperature_c IS NULL OR water_temperature_c BETWEEN -5 AND 45',
)
@Check(
  'ck_dive_participations__visibility_m',
  'visibility_m IS NULL OR visibility_m BETWEEN 0 AND 100',
)
@Check('ck_dive_participations__gas_mix', "gas_mix IN ('AIR', 'NITROX32', 'NITROX36', 'OTHER')")
@Check('ck_dive_participations__notes', 'notes IS NULL OR char_length(notes) <= 5000')
export class DiveParticipation extends SyncedEntity {
  /** UUIDv7 generated by the client (offline creation). */
  @PrimaryColumn('uuid', { name: 'id', primaryKeyConstraintName: 'pk_dive_participations' })
  id: string;

  @Column({ type: 'uuid', name: 'dive_event_id' })
  diveEventId: string;

  @ManyToOne(() => DiveEvent, { onDelete: 'CASCADE', nullable: false })
  @JoinColumn({
    name: 'dive_event_id',
    foreignKeyConstraintName: 'fk_dive_participations__dive_event_id',
  })
  diveEvent?: Relation<DiveEvent>;

  @Column({ type: 'uuid', name: 'diver_id' })
  diverId: string;

  @ManyToOne(() => Diver, { onDelete: 'CASCADE', nullable: false })
  @JoinColumn({ name: 'diver_id', foreignKeyConstraintName: 'fk_dive_participations__diver_id' })
  diver?: Relation<Diver>;

  /** Snapshot set at entry time (D-09): never resynchronised with the diver's current level. */
  @Column({ type: 'uuid', name: 'certification_level_id' })
  certificationLevelId: string;

  // Deliberately not indexed: levels are never deleted.
  @ManyToOne(() => CertificationLevel, { onDelete: 'RESTRICT', nullable: false })
  @JoinColumn({
    name: 'certification_level_id',
    foreignKeyConstraintName: 'fk_dive_participations__certification_level_id',
  })
  certificationLevel?: Relation<CertificationLevel>;

  @Column({
    type: 'numeric',
    name: 'max_depth_m',
    precision: 4,
    scale: 1,
    transformer: numericTransformer,
  })
  maxDepthM: number;

  @Column({ type: 'smallint', name: 'duration_min' })
  durationMin: number;

  @Column({
    type: 'numeric',
    name: 'water_temperature_c',
    precision: 3,
    scale: 1,
    nullable: true,
    transformer: numericTransformer,
  })
  waterTemperatureC: number | null;

  @Column({ type: 'smallint', name: 'visibility_m', nullable: true })
  visibilityM: number | null;

  @Column({ type: 'text', name: 'gas_mix' })
  gasMix: GasMix;

  @Column({ type: 'boolean', name: 'has_decompression', default: false })
  hasDecompression: boolean;

  /** No default on purpose (D-11): "stops respected" must be entered, never assumed. */
  @Column({ type: 'boolean', name: 'stops_ok' })
  stopsOk: boolean;

  @Column({ type: 'text', name: 'notes', nullable: true })
  notes: string | null;
}
