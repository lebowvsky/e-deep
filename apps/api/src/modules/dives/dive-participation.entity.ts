import {
  Check,
  Column,
  Entity,
  Index,
  JoinColumn,
  ManyToOne,
  PrimaryColumn,
  Unique,
  type Relation,
} from 'typeorm';
import { numericTransformer } from '../../common/database/numeric.transformer';
import { SyncedEntity } from '../../common/database/timestamped.entity';
import { CertificationLevel } from '../certification-levels/certification-level.entity';
import { Diver } from '../divers/diver.entity';
import { DiveEvent } from './dive-event.entity';
import type { SuitType, TankMaterial } from './dive-detail-lists';
import type { GasMix } from './gas-mix';

/** Health data (GDPR art. 9): one diver's own measures for a dive event. Never log its values. */
@Entity({ name: 'dive_participations' })
// Not partial: a participation removed then re-added is restored, not recreated. Covers the event FK.
@Unique('uq_dive_participations__dive_event_id_diver_id', ['diveEventId', 'diverId'])
// Target of the composite FK from `dive_buddies`; also covers the `diver_id` FK.
@Unique('uq_dive_participations__diver_id_id', ['diverId', 'id'])
@Index('idx_dive_participations__diver_id_dive_event_id', ['diverId', 'diveEventId'], {
  where: 'deleted_at IS NULL',
})
@Index('idx_dive_participations__diver_id_updated_at_id', ['diverId', 'updatedAt', 'id'])
@Check('ck_dive_participations__max_depth_m', 'max_depth_m > 0 AND max_depth_m <= 350')
@Check('ck_dive_participations__duration_min', 'duration_min > 0 AND duration_min <= 1440')
@Check(
  'ck_dive_participations__water_temperature_c',
  'water_temperature_c IS NULL OR water_temperature_c BETWEEN -5 AND 45',
)
@Check(
  'ck_dive_participations__visibility_m',
  'visibility_m IS NULL OR visibility_m BETWEEN 0 AND 100',
)
@Check('ck_dive_participations__gas_mix', "gas_mix IN ('AIR', 'NITROX32', 'NITROX36', 'OTHER')")
@Check('ck_dive_participations__notes', 'notes IS NULL OR char_length(notes) <= 5000')
@Check(
  'ck_dive_participations__surface_water_temperature_c',
  'surface_water_temperature_c IS NULL OR surface_water_temperature_c BETWEEN -5 AND 45',
)
@Check(
  'ck_dive_participations__safety_stop_duration_min',
  'safety_stop_duration_min IS NULL OR (safety_stop_duration_min > 0 AND safety_stop_duration_min <= 60 AND safety_stop_duration_min < duration_min)',
)
@Check(
  'ck_dive_participations__safety_stop_depth_m',
  'safety_stop_depth_m IS NULL OR (safety_stop_depth_m > 0 AND safety_stop_depth_m <= 20 AND safety_stop_depth_m <= max_depth_m)',
)
@Check(
  'ck_dive_participations__safety_stop',
  '(safety_stop_duration_min IS NULL) = (safety_stop_depth_m IS NULL)',
)
@Check(
  'ck_dive_participations__o2_percent',
  "o2_percent IS NULL OR (gas_mix = 'OTHER' AND o2_percent > 0 AND o2_percent <= 100)",
)
@Check(
  'ck_dive_participations__tank_volume_l',
  'tank_volume_l IS NULL OR (tank_volume_l > 0 AND tank_volume_l <= 30)',
)
@Check(
  'ck_dive_participations__tank_material',
  "tank_material IS NULL OR tank_material IN ('STEEL', 'ALUMINIUM')",
)
@Check(
  'ck_dive_participations__start_pressure_bar',
  'start_pressure_bar IS NULL OR (start_pressure_bar > 0 AND start_pressure_bar <= 350)',
)
@Check(
  'ck_dive_participations__end_pressure_bar',
  'end_pressure_bar IS NULL OR (end_pressure_bar BETWEEN 0 AND 350 AND (start_pressure_bar IS NULL OR end_pressure_bar <= start_pressure_bar))',
)
@Check(
  'ck_dive_participations__suit_type',
  "suit_type IS NULL OR suit_type IN ('WET', 'SEMI_DRY', 'DRY')",
)
@Check(
  'ck_dive_participations__suit_thickness_mm',
  'suit_thickness_mm IS NULL OR (suit_thickness_mm > 0 AND suit_thickness_mm <= 15)',
)
@Check('ck_dive_participations__weight_kg', 'weight_kg IS NULL OR weight_kg BETWEEN 0 AND 40')
export class DiveParticipation extends SyncedEntity {
  /** UUIDv7 generated by the client (offline creation). */
  @PrimaryColumn('uuid', { name: 'id', primaryKeyConstraintName: 'pk_dive_participations' })
  id: string;

  @Column({ type: 'uuid', name: 'dive_event_id' })
  diveEventId: string;

  @ManyToOne(() => DiveEvent, { onDelete: 'CASCADE', nullable: false })
  @JoinColumn({
    name: 'dive_event_id',
    foreignKeyConstraintName: 'fk_dive_participations__dive_event_id',
  })
  diveEvent?: Relation<DiveEvent>;

  @Column({ type: 'uuid', name: 'diver_id' })
  diverId: string;

  @ManyToOne(() => Diver, { onDelete: 'CASCADE', nullable: false })
  @JoinColumn({ name: 'diver_id', foreignKeyConstraintName: 'fk_dive_participations__diver_id' })
  diver?: Relation<Diver>;

  /** Snapshot set at entry time (D-09): never resynchronised with the diver's current level. */
  @Column({ type: 'uuid', name: 'certification_level_id' })
  certificationLevelId: string;

  // Deliberately not indexed: levels are never deleted.
  @ManyToOne(() => CertificationLevel, { onDelete: 'RESTRICT', nullable: false })
  @JoinColumn({
    name: 'certification_level_id',
    foreignKeyConstraintName: 'fk_dive_participations__certification_level_id',
  })
  certificationLevel?: Relation<CertificationLevel>;

  @Column({
    type: 'numeric',
    name: 'max_depth_m',
    precision: 4,
    scale: 1,
    transformer: numericTransformer,
  })
  maxDepthM: number;

  @Column({ type: 'smallint', name: 'duration_min' })
  durationMin: number;

  @Column({
    type: 'numeric',
    name: 'water_temperature_c',
    precision: 3,
    scale: 1,
    nullable: true,
    transformer: numericTransformer,
  })
  waterTemperatureC: number | null;

  @Column({ type: 'smallint', name: 'visibility_m', nullable: true })
  visibilityM: number | null;

  @Column({ type: 'text', name: 'gas_mix' })
  gasMix: GasMix;

  @Column({ type: 'boolean', name: 'has_decompression', default: false })
  hasDecompression: boolean;

  /** No default on purpose (D-11): "stops respected" must be entered, never assumed. */
  @Column({ type: 'boolean', name: 'stops_ok' })
  stopsOk: boolean;

  @Column({ type: 'text', name: 'notes', nullable: true })
  notes: string | null;

  // Detail of the dive (D-15 to D-17). Every column is nullable without default: `NULL` = not
  // entered. Health data: never logged.

  /** Water temperature at the surface; `water_temperature_c` stays the bottom one. */
  @Column({
    type: 'numeric',
    name: 'surface_water_temperature_c',
    precision: 3,
    scale: 1,
    nullable: true,
    transformer: numericTransformer,
  })
  surfaceWaterTemperatureC: number | null;

  /** Safety stop: duration and depth are both set or both `NULL` (RG-25). */
  @Column({ type: 'smallint', name: 'safety_stop_duration_min', nullable: true })
  safetyStopDurationMin: number | null;

  @Column({
    type: 'numeric',
    name: 'safety_stop_depth_m',
    precision: 3,
    scale: 1,
    nullable: true,
    transformer: numericTransformer,
  })
  safetyStopDepthM: number | null;

  /** Declared by the diver, never derived from the log (D-17). No default on purpose. */
  @Column({ type: 'boolean', name: 'is_repetitive', nullable: true })
  isRepetitive: boolean | null;

  /** Only for `gas_mix = 'OTHER'` (RG-23): Air and Nitrox imply their percentage (3NF). */
  @Column({
    type: 'numeric',
    name: 'o2_percent',
    precision: 4,
    scale: 1,
    nullable: true,
    transformer: numericTransformer,
  })
  o2Percent: number | null;

  @Column({
    type: 'numeric',
    name: 'tank_volume_l',
    precision: 3,
    scale: 1,
    nullable: true,
    transformer: numericTransformer,
  })
  tankVolumeL: number | null;

  @Column({ type: 'text', name: 'tank_material', nullable: true })
  tankMaterial: TankMaterial | null;

  @Column({ type: 'smallint', name: 'start_pressure_bar', nullable: true })
  startPressureBar: number | null;

  /** At most the start pressure when both are set (RG-24); consumed bar are computed, never stored. */
  @Column({ type: 'smallint', name: 'end_pressure_bar', nullable: true })
  endPressureBar: number | null;

  @Column({ type: 'text', name: 'suit_type', nullable: true })
  suitType: SuitType | null;

  @Column({
    type: 'numeric',
    name: 'suit_thickness_mm',
    precision: 3,
    scale: 1,
    nullable: true,
    transformer: numericTransformer,
  })
  suitThicknessMm: number | null;

  @Column({
    type: 'numeric',
    name: 'weight_kg',
    precision: 3,
    scale: 1,
    nullable: true,
    transformer: numericTransformer,
  })
  weightKg: number | null;
}
