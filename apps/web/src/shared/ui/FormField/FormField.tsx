import { useId, type ReactNode } from 'react';
import { cx } from '@/shared/lib/classNames';
import { Icon } from '@/shared/ui/Icon';
import { FormFieldContext, type FieldStatus, type FormFieldContextValue } from './formFieldContext';
import styles from './FormField.module.scss';

export interface FormFieldProps {
  label: ReactNode;
  /** Decorative `*` next to the label; the control gets `aria-required`. */
  required?: boolean;
  /** Help under the control, replaced by the error or the warning when there is one. */
  hint?: ReactNode;
  /** Says what to do: danger look, icon in the field, `aria-invalid`. Wins over `warning`. */
  error?: ReactNode;
  /** Non-blocking warning (depth beyond the level, duplicate dive number). */
  warning?: ReactNode;
  /** Read-only control, shown with its help (e.g. « Air = 21 % »). */
  locked?: boolean;
  /** Control id, for links from an error summary. Generated by default. */
  id?: string;
  /** One control that reads its wiring with `useFormField` (every `shared/ui` field does). */
  children: ReactNode;
  className?: string | undefined;
}

const statusOf = (error: ReactNode, warning: ReactNode): FieldStatus => {
  if (error) return 'error';
  if (warning) return 'warning';
  return 'default';
};

/**
 * Label above, control, then help or message under it (dive-form.jsx · Field). Ids, `aria-invalid`,
 * `aria-describedby` and `aria-required` reach the control through context.
 */
export function FormField({
  label,
  required = false,
  hint,
  error,
  warning,
  locked = false,
  id,
  children,
  className,
}: FormFieldProps) {
  const generatedId = useId();
  const controlId = id ?? `${generatedId}-control`;
  const labelId = `${generatedId}-label`;
  const descriptionId = `${generatedId}-description`;

  const status = statusOf(error, warning);
  const message = status === 'error' ? error : status === 'warning' ? warning : null;
  const description = message ?? hint;

  const field: FormFieldContextValue = {
    controlId,
    labelId,
    describedBy: description ? descriptionId : undefined,
    status,
    required,
    locked,
  };

  return (
    <div className={cx(styles.field, className)}>
      <label id={labelId} htmlFor={controlId} className={styles.label}>
        {label}
        {required && (
          <span className={styles.required} aria-hidden="true">
            {' *'}
          </span>
        )}
      </label>
      <FormFieldContext value={field}>{children}</FormFieldContext>
      {message ? (
        <p id={descriptionId} className={cx(styles.message, styles[status])}>
          <Icon name={status === 'error' ? 'alert' : 'info'} size="sm" className={styles.icon} />
          <span>{message}</span>
        </p>
      ) : (
        hint && (
          <p id={descriptionId} className={styles.hint}>
            {hint}
          </p>
        )
      )}
    </div>
  );
}
