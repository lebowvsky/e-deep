// Contract of the dive sites (`/api/sites`, D31, D-33). A site is private to its owner. Every
// field is present, `null` when not entered (D-22).

/** Kind of site (RG-31). */
export type SiteType = 'tombant' | 'epave' | 'sec' | 'grotte' | 'herbier' | 'autre';

/**
 * Where the site was created, immutable (RG-34): `quick` by its name from the dive form, `full`
 * from the map.
 */
export type SiteOrigin = 'quick' | 'full';

/** A live site of the current diver. No zone (computed by the front) nor statistics. */
export interface SiteResponse {
  id: string;
  name: string;
  /** Town or spot (e.g. `Calvi`). */
  locality: string | null;
  region: string | null;
  /** Sea or area entered (e.g. `Méditerranée`), distinct from the zone the front computes. */
  area: string | null;
  /** Both set or both `null` (D-23). */
  latitude: number | null;
  longitude: number | null;
  type: SiteType | null;
  /** Usual depths of the site (m, one decimal), not the diver's own; min ≤ max (RG-32). */
  depthMinM: number | null;
  depthMaxM: number | null;
  /** « Accès & conseils », 1 to 2 000 characters. */
  accessNotes: string | null;
  createdVia: SiteOrigin;
  /** ISO 8601 instants (UTC). */
  createdAt: string;
  updatedAt: string;
}

/** `GET /api/sites`: every live site of the diver, by name (then id). */
export interface SiteListResponse {
  sites: SiteResponse[];
}

/**
 * Body of `PUT /api/sites/:id`: a full replacement, every field required, `null` when not entered
 * (D-22). `id` equals `:id`. The origin cannot change (RG-34).
 */
export interface SiteWriteRequest {
  /** Generated by the client (D22). */
  id: string;
  name: string;
  locality: string | null;
  region: string | null;
  area: string | null;
  latitude: number | null;
  longitude: number | null;
  type: SiteType | null;
  depthMinM: number | null;
  depthMaxM: number | null;
  accessNotes: string | null;
}

/** Body of `POST /api/sites`: `201`, or `200` when the same creation is received again. */
export interface SiteCreateRequest extends SiteWriteRequest {
  createdVia: SiteOrigin;
}

/**
 * Body of `POST /api/sites/:id/merge`: every dive of `:id` moves to `targetId`, whose empty fields
 * are completed, then `:id` is deleted (RG-35). Answers the target (`SiteResponse`).
 */
export interface SiteMergeRequest {
  targetId: string;
}
